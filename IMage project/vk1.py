target_cols = 100

# Calculate original dimensions
original_rows = len(lines)
original_cols = len(lines[0]) if lines else 0

print(f"Original dimensions: {original_rows} rows x {original_cols} columns")
print(f"Target dimensions: {target_rows} rows x {target_cols} columns")

# Create a 2D array for the compressed result
compressed = []

# Calculate row sampling step
row_step = original_rows / target_rows

# For each target row
for target_row in range(target_rows):
    # Find which original row to sample
    original_row_index = int(target_row * row_step)
    if original_row_index >= original_rows:
        original_row_index = original_rows - 1
    
    # Get the original row
    original_row = lines[original_row_index]
    
    # Calculate column sampling step
    col_step = len(original_row) / target_cols
    
    # Build the compressed row
    compressed_row = []
    for target_col in range(target_cols):
        # Find which original column to sample
        original_col_index = int(target_col * col_step)
        if original_col_index >= len(original_row):
            original_col_index = len(original_row) - 1
        
        # Add the character
        compressed_row.append(original_row[original_col_index])
    
    # Add the compressed row to result
    compressed.append(''.join(compressed_row))

# Print the compressed result
